import optuna
import lightgbm as lgb
from sklearn.model_selection import cross_val_score

optuna.logging.set_verbosity(optuna.logging.WARNING)  # çıktıyı sessizleştir

def objective(trial):
    params = {
        "n_estimators":     trial.suggest_int("n_estimators", 100, 800),
        "learning_rate":    trial.suggest_float("learning_rate", 0.01, 0.3, log=True),
        "max_depth":        trial.suggest_int("max_depth", 2, 8),
        "num_leaves":       trial.suggest_int("num_leaves", 7, 63),
        "min_child_samples":trial.suggest_int("min_child_samples", 5, 50),
        "subsample":        trial.suggest_float("subsample", 0.6, 1.0),
        "colsample_bytree": trial.suggest_float("colsample_bytree", 0.6, 1.0),
        "random_state": 42, "n_jobs": -1, "verbose": -1,
    }
    model = lgb.LGBMRegressor(**params)
    # TimeSeriesSplit ile CV RMSE (negatif), ortalamasını al
    scores = cross_val_score(model, X_train, y_train, cv=tscv,
                             scoring="neg_root_mean_squared_error")
    return -scores.mean()   # Optuna minimize edecek

study = optuna.create_study(direction="minimize")
study.optimize(objective, n_trials=40, show_progress_bar=True)

print("En iyi parametreler:", study.best_params)
print("En iyi CV RMSE:", study.best_value)

# En iyi parametrelerle modeli eğit ve test et
best_lgb = lgb.LGBMRegressor(**study.best_params, random_state=42, n_jobs=-1, verbose=-1)
best_lgb.fit(X_train, y_train)
lgb_pred = best_lgb.predict(X_test)
results.append(evaluate(y_test.values, lgb_pred, "LightGBM"))

