import yfinance as yf
import numpy as np
import pandas as pd

# --- Adım 1: Veri ---
df = yf.download("^GSPC", start="2010-01-01", end="2024-12-31", auto_adjust=True)
df = df[["Close", "Volume"]].dropna()
df.columns = ["close", "volume"]
df["ret"] = np.log(df["close"]).diff()
df = df.dropna()

# --- Adım 2: Hedef (gelecek 5 günün gerçekleşen oynaklığı) ---
HORIZON = 5
df["target_vol"] = df["ret"].rolling(HORIZON).std().shift(-HORIZON) * np.sqrt(252)

# --- Adım 3: Öznitelikler (yalnızca geçmiş veriden) ---
for w in [5, 10, 22, 66]:
    df[f"vol_{w}"] = df["ret"].rolling(w).std() * np.sqrt(252)
df["abs_ret"] = df["ret"].abs()
for lag in [1, 2, 3, 5]:
    df[f"abs_ret_lag{lag}"] = df["abs_ret"].shift(lag)
df["ret_lag1"] = df["ret"].shift(1)
df["vol_chg"] = np.log(df["volume"] + 1).diff()   # +1 ile log(0) sorununu baştan engelledik
df["vol_ma22"] = df["volume"].rolling(22).mean()
df["dow"] = df.index.dayofweek
df["month"] = df.index.month

# --- Temizlik: NaN + inf birlikte ---
df = df.replace([np.inf, -np.inf], np.nan).dropna()

print("Son boyut:", df.shape)
print("target_vol var mı?:", "target_vol" in df.columns)
print("inf sayısı:", np.isinf(df.select_dtypes(include=[np.number])).sum().sum())
df.head()

from sklearn.model_selection import TimeSeriesSplit

# Öznitelik / hedef ayrımı
feature_cols = [c for c in df.columns
                if c not in ["close", "volume", "ret", "abs_ret", "target_vol"]]
X = df[feature_cols]
y = df["target_vol"]

print("Kullanılan öznitelikler:", feature_cols)

# Kronolojik bölme: ilk %80 eğitim, son %20 test
split_idx = int(len(df) * 0.8)
X_train, X_test = X.iloc[:split_idx], X.iloc[split_idx:]
y_train, y_test = y.iloc[:split_idx], y.iloc[split_idx:]

print(f"Eğitim: {X_train.shape[0]} satır  |  Test: {X_test.shape[0]} satır")
print(f"Eğitim dönemi: {X_train.index.min().date()} → {X_train.index.max().date()}")
print(f"Test dönemi:  {X_test.index.min().date()} → {X_test.index.max().date()}")

# Doğrulama için zaman serisi cross-validation
tscv = TimeSeriesSplit(n_splits=5)

from sklearn.metrics import mean_squared_error, mean_absolute_error, r2_score

def evaluate(y_true, y_pred, name=""):
    rmse = np.sqrt(mean_squared_error(y_true, y_pred))
    mae  = mean_absolute_error(y_true, y_pred)
    mape = np.mean(np.abs((y_true - y_pred) / y_true)) * 100
    r2   = r2_score(y_true, y_pred)
    print(f"{name:20s} | RMSE: {rmse:.4f} | MAE: {mae:.4f} | MAPE: {mape:.2f}% | R²: {r2:.4f}")
    return {"model": name, "RMSE": rmse, "MAE": mae, "MAPE": mape, "R2": r2}

results = []

# --- Baseline 1: Naive (son 5 günün oynaklığı = gelecek oynaklık tahmini) ---
naive_pred = X_test["vol_5"].values
results.append(evaluate(y_test.values, naive_pred, "Naive (vol_5)"))

from sklearn.linear_model import Ridge
from sklearn.preprocessing import StandardScaler
from sklearn.pipeline import Pipeline
from sklearn.model_selection import GridSearchCV

# Pipeline: önce ölçekle, sonra Ridge
ridge_pipe = Pipeline([
    ("scaler", StandardScaler()),
    ("model", Ridge())
])

# alpha için arama uzayı
param_grid = {"model__alpha": [0.001, 0.01, 0.1, 1, 10, 100, 1000]}

# Zaman serisi CV ile, RMSE'yi minimize ederek ara
ridge_search = GridSearchCV(
    ridge_pipe,
    param_grid,
    cv=tscv,                              # Adım 4'teki TimeSeriesSplit
    scoring="neg_root_mean_squared_error",
    n_jobs=-1
)
ridge_search.fit(X_train, y_train)

print("En iyi alpha:", ridge_search.best_params_)
print("CV RMSE:", -ridge_search.best_score_)

# Test setinde değerlendir
ridge_pred = ridge_search.predict(X_test)
results.append(evaluate(y_test.values, ridge_pred, "Ridge"))

