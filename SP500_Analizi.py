from arch import arch_model

# GARCH getirileri yüzde olarak ister (sayısal stabilite için)
ret_pct = df["ret"] * 100
split_idx = int(len(df) * 0.8)   # ML ile aynı bölme noktası

# Test dönemindeki her gün için "kayan pencere" GARCH tahmini
garch_preds = []
test_index = df.index[split_idx:]

for i in range(split_idx, len(df)):
    # O güne kadarki tüm getirilerle modeli eğit (genişleyen pencere)
    train_ret = ret_pct.iloc[:i]
    am = arch_model(train_ret, vol="Garch", p=1, q=1, dist="normal")
    res = am.fit(disp="off")
    # 5 gün ileri tahmin
    fc = res.forecast(horizon=HORIZON, reindex=False)
    # 5 günlük varyans toplamı → std → yıllıklaştır → %100'e geri böl
    var_5d = fc.variance.values[-1, :].sum()
    vol_5d_annual = np.sqrt(var_5d) / 100 * np.sqrt(252 / HORIZON)
    garch_preds.append(vol_5d_annual)

garch_preds = np.array(garch_preds)
results.append(evaluate(y_test.values, garch_preds, "GARCH(1,1)"))